// Forge V2 normalization metadata:
// loadingType is the only field that affects how normalization interprets
// load and bodyweight context. movementClass, equipmentType, and laterality
// are descriptive only in V2.
//
// Normalization must NOT apply multipliers based on:
// - compound vs isolation
// - machine vs free weight
// - unilateral vs bilateral
export type LoadingTypeV2 =
  | "external"
  | "bodyweight"
  | "weighted_bodyweight"
  | "assisted_bodyweight";

export type MovementClassV2 =
  | "compound"
  | "isolation";

export type EquipmentTypeV2 =
  | "barbell"
  | "dumbbell"
  | "cable"
  | "machine"
  | "smith"
  | "bodyweight"
  | "band"
  | "other";

export type LateralityV2 =
  | "bilateral"
  | "unilateral"
  | "alternating";

export type ExerciseNormalizationMetaV2 = {
  loadingType: LoadingTypeV2;
  movementClass: MovementClassV2;
  equipmentType?: EquipmentTypeV2;
  laterality?: LateralityV2;
};

