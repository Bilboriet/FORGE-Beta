const familyByMuscle = new Map<ExerciseDatabaseMuscleKey, MuscleGroup>(
  exerciseDatabaseMuscles.map((item) => [item.id, item.family] as const)
);

export function toExerciseRef(entry: ExerciseDatabaseEntry): ExerciseRef {
  return {
    id: entry.id,
    name: entry.displayName,
    muscleGroup: familyByMuscle.get(entry.muscleGroup) ?? "other",
  };
}

export const exerciseDatabaseRefs: ExerciseRef[] = exerciseDatabase.map(toExerciseRef);
export const exerciseDatabaseById = new Map(exerciseDatabase.map((entry) => [entry.id, entry] as const));

function inferLoadingTypeV2(entry: ExerciseDatabaseEntry): LoadingTypeV2 {
  const biasTags = new Set((entry.biasTags ?? []).map((value) => value.toLowerCase()));
  const equipment = new Set((entry.equipment ?? []).map((value) => value.toLowerCase()));
  const id = entry.id.toLowerCase();

  if (
    biasTags.has("assisted") ||
    Array.from(equipment).some((value) => value.includes("assisted"))
  ) {
    return "assisted_bodyweight";
  }

  if (
    biasTags.has("bodyweight") ||
    equipment.has("bodyweight") ||
    equipment.has("pull_up_bar") ||
    equipment.has("dip_bars") ||
    id.includes("pull_up") ||
    id.includes("chin_up") ||
    id.includes("push_up")
  ) {
    return "bodyweight";
  }

  return "external";
}

export function getExerciseNormalizationMetaV2(exerciseId: string): ExerciseNormalizationMetaV2 {
  const entry = exerciseDatabaseById.get(exerciseId);
  if (!entry) {
    return DEFAULT_EXERCISE_NORMALIZATION_META_V2;
  }

  if (entry.normalizationMeta) {
    return entry.normalizationMeta;
  }

  return {
    loadingType: inferLoadingTypeV2(entry),
    // Fallback metadata stays deliberately low-detail in V2.
    // Only loadingType currently changes normalization behavior, so missing
    // explicit metadata should not silently invent richer equipment or
    // laterality claims that the active coach path does not need yet.
    movementClass: DEFAULT_EXERCISE_NORMALIZATION_META_V2.movementClass,
    equipmentType: DEFAULT_EXERCISE_NORMALIZATION_META_V2.equipmentType,
    laterality: DEFAULT_EXERCISE_NORMALIZATION_META_V2.laterality,
  };
}
