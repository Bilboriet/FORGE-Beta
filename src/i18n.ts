const DICTS: Record<Lang, Dict> = { no: NO, en: EN, es: ES };

// dev-only: warn once per missing key per language
const _missingWarned = new Set<string>();

type Vars = Record<string, string | number | boolean | null | undefined>;

function formatVars(template: string, vars?: Vars) {
  if (!vars) return template;
  return template.replace(/\{(.*?)\}/g, (_m, k) => {
    const v = (vars as any)[String(k)];
    if (v == null) return "";
    return String(v);
  });
}

export function t(lang: Lang, key: string, vars?: Vars): string {
  const dict = DICTS[lang] ?? NO;

  // dev-only warnings when a key is missing in the selected language but exists in NO
  // (NO is the canonical fallback)
  try {
    const isDev = typeof import.meta !== "undefined" && (import.meta as any).env?.DEV;
    if (isDev && lang !== "no" && dict[key] == null && NO[key] != null) {
      const token = `${lang}:${key}`;
      if (!_missingWarned.has(token)) {
        _missingWarned.add(token);
        // eslint-disable-next-line no-console
        console.warn(`[i18n] Missing '${key}' in '${lang}'. Falling back to NO.`);
      }
    }
  } catch {
    // ignore
  }

  const out = dict[key] ?? NO[key] ?? key;
  return formatVars(out, vars);
}
